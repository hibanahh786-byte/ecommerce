# Database Setup (MySQL with automatic fallback if MySQL server is not running)
DB_ENGINE = os.environ.get('DB_ENGINE', 'mysql').lower()

def get_database_config():
    if DB_ENGINE == 'sqlite3':
        return {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    
    mysql_config = {
        'ENGINE': 'django.db.backends.mysql',
        'NAME': os.environ.get('DB_NAME', 'ecommerce_db'),
        'USER': os.environ.get('DB_USER', 'root'),
        'PASSWORD': os.environ.get('DB_PASSWORD', ''),
        'HOST': os.environ.get('DB_HOST', '127.0.0.1'),
        'PORT': os.environ.get('DB_PORT', '3306'),
        'OPTIONS': {
            'charset': 'utf8mb4',
        },
    }

    try:
        conn = pymysql.connect(
            host=mysql_config['HOST'],
            user=mysql_config['USER'],
            password=mysql_config['PASSWORD'],
            port=int(mysql_config['PORT']),
            connect_timeout=2
        )
        cursor = conn.cursor()
        cursor.execute(f"CREATE DATABASE IF NOT EXISTS `{mysql_config['NAME']}` CHARACTER SET utf8mb4;")
        conn.commit()
        conn.close()
        return mysql_config
    except Exception as e:
        print(f"[Database Info] MySQL is not reachable ({e}). Using SQLite for local testing.")
        return {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }

